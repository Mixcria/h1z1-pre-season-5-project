        "    /// ARMED fire group. <c>1.0f</c> is the client's own preset and means \"no zoom\".",
        "    /// <para>",
        "    /// The mechanism is [P] - <c>FUN_141488490</c> reads that offset under the key whose",
        "    /// initialiser string is <c>\"FireMode.DefaultZoom\"</c> and <c>FUN_1411c8740</c>",
        "    /// interpolates the character's <c>+0x55a4</c> toward it - but NO August sheet carries a",
