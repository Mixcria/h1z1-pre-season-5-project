        "/// <param name=\"RefireTimeMs\"><c>rec+0x40</c> <c>FireMode.RefireTime</c> [P].</param>",
        "/// <param name=\"ReloadTimeMs\"><c>rec+0x60</c> <c>FireMode.ReloadTime</c> [P].</param>",
        "/// <param name=\"ClipSize\">",
        "/// The client's own <c>CLIP_SIZE</c> for the group's first item - what the weapon",
        "/// definition's ammo slot carries as <c>AmmoSlot.ClipSize</c>.",
        "/// </param>",
        "/// <param name=\"IronSights\">",
        "/// <c>rec+0x20</c> bit <c>0x04</c> <c>IRON_SIGHTS</c> [P]. RULING: mode index 1 is the ADS",
        "/// mode - it is the index the August client's own right-click sends in all 145 captured",
        "/// <c>82 0c</c> packets, and the owner's Z1 reads the same index as aim-down.",
        "/// </param>",
        "/// <param name=\"AmmoSlot\"><c>rec+0x30</c> <c>AMMO_SLOT</c> [P]. One slot per gun, so 0.</param>",
        "/// <param name=\"EffectGroup\">",
        "/// <c>rec+0x104</c> <c>EFFECT_GROUP</c> - the <c>FireModeEffectGroups</c> GROUP_ID the client",
        "/// resolves to a fire composite effect (the muzzle flash and the gunshot audio) when this fire",
        "/// group FIRES. It is the fire-group id itself, shipped only for a group with a non-zero",
        "/// <c>fire</c> row (groups 1..21/23/24); a group with no row (every group &gt; 24, e.g. the",
        "/// AK-47's 51) is a gap and ships 0. Shipping 0 was the owner's \"no noise of being shot\" -",
        "/// the client logs \"missing effect definition for Id #0\". RULING D234.",
        "/// </param>",
        "public readonly record struct AugustFireModeFact(",
        "    uint FireModeId,",
        "    uint FireGroupId,",
        "    int ModeIndex,",
        "    uint SourceItemId,",
        "    uint DefinitionId,",
        "    int RefireTimeMs,",
        "    int ReloadTimeMs,",
        "    int ClipSize,",
        "    bool IronSights,",
        "    int AmmoSlot,",
        "    uint EffectGroup);",
        "",
        "/// <summary>",
        f"/// The {len(rows)} fire modes of the {doc['counts']['fireGroups']} fire groups the client's own",
        "/// <c>ClientItemDatasheetData.txt</c> names, in (fire group, mode index) order.",
        "/// </summary>",
        "public static class AugustFireModeFacts",
        "{",
        f"    /// <summary>Modes per fire group - D159, and <c>AugustWeaponTable.FireModesPerGroup</c>.</summary>",
        f"    public const int ModesPerGroup = {doc['fireModesPerGroup']};",
        "",
        "    /// <summary>",
        "    /// <b>RULING - the ADS zoom multiplier</b> Cranberry writes into <c>rec+0x128</c>",
