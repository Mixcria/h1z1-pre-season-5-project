        "/// <param name=\"SourceItemId\">The datasheet row the timings came from.</param>",
        "/// <param name=\"DefinitionId\">",
        "/// <c>rec+0x18</c> - the fire mode's OWN id, and the primary key of list 4. Equal to",
        "/// <paramref name=\"FireModeId\"/>; see <c>FireModeRecord.DefinitionId</c> for the three",
        "/// functions that read it.",
