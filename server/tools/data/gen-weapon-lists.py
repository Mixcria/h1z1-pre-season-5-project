        "    /// the client itself uses to choose <c>ADSMouseSensitivity</c> over",
        "    /// <c>scopedMouseSensitivity</c> (<c>_DAT_143275150 = 2.0f</c> in <c>FUN_140e40090</c>",
        "    /// and <c>FUN_140e4a010</c>). <c>CRANBERRY_WEAPON_ADS_ZOOM</c> overrides it and",
        "    /// <c>CRANBERRY_WEAPON_ADS_FOV=0</c> reverts every mode to <c>1.0f</c>.",
        "    /// </para>",
        "    /// </summary>",
        f"    public const float AdsZoom = {doc['adsZoom']}f;",
        "",
        "    /// <summary>",
        "    /// <b>RULING - the ADS FIRST-PERSON switch.</b> <c>FORCE_FP_SCOPE</c>",
        "    /// (<c>rec+0x2dc</c>) on the PRIMARY mode of an ARMED fire group. [P]:",
        "    /// <c>FUN_14158ad50:17</c> reads that byte off the LIVE fire-mode record and",
        "    /// <c>FUN_14158b700</c> - the <c>Infantry</c> / <c>SecondaryFire</c> handler, bound to",
        "    /// <c>Mouse_1</c> as <c>UI.WeaponOptic</c> - branches on it: set, it calls",
        "    /// <c>FUN_14158ab50</c>, which switches the camera to <c>0x1e</c> (first person) while",
        "    /// the button is held and back to <c>0x24</c> on release; clear, it calls the aim",
        "    /// vtable slot <c>+0x370</c> instead, which is the <c>82 0c SwitchFireModeRequest</c>",
        "    /// path. The two are EXCLUSIVE (<c>14158bb2d JZ 14158bc1f</c>), so this suppresses the",
        "    /// iron-sights mode - and with it <see cref=\"AdsZoom\"/> - while it is on.",
        "    /// </summary>",
        f"    public const bool AdsFirstPerson = {str(doc['adsFirstPerson']).lower()};",
        "",
        "    /// <summary>",
        "    /// <b>RULING - the aimed first-person field of view, in DEGREES</b>, for",
        "    /// <c>FP_CAMERA_FOV</c> / <c>FP_CR_CAMERA_FOV</c> / <c>FP_PR_CAMERA_FOV</c>",
